import { readFileSync, writeFileSync, readdirSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname  = path.dirname(__filename);

const schemaDir = path.join(__dirname, "prisma/models");

// Read all .prisma files dynamically so new models are included automatically.
// User.prisma is placed first so its relations resolve cleanly.
const allFiles = readdirSync(schemaDir)
  .filter((f) => f.endsWith(".prisma"))
  .sort((a, b) => {
    if (a === "User.prisma") return -1;
    if (b === "User.prisma") return  1;
    return a.localeCompare(b);
  });

let mergedSchema =
  "// This file is auto-generated by merge-schema.ts. Do not edit directly.\n\n" +
  "generator client {\n  provider = \"prisma-client-js\"\n}\n\n" +
  "datasource db {\n  provider = \"postgresql\"\n  url      = env(\"DATABASE_URL\")\n}\n\n";

for (const file of allFiles) {
  const content = readFileSync(path.join(schemaDir, file), "utf-8");
  mergedSchema += "\n" + content + "\n";
}

writeFileSync(path.join(__dirname, "prisma/schema.prisma"), mergedSchema);

const names = allFiles.map((f) => f.replace(".prisma", "")).join(", ");
console.log("Successfully merged " + allFiles.length + " schema files into prisma/schema.prisma!");
console.log("Models included: " + names);
